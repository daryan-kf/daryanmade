import { chromium } from "@playwright/test";
import { mkdir } from "node:fs/promises";
await mkdir("artifacts", { recursive: true });
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto("http://127.0.0.1:3000", { waitUntil: "networkidle" });
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(1800);
await page.screenshot({ path: "artifacts/home-desktop.png" });
await page.screenshot({ path: "artifacts/home-desktop-full.png", fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto("http://127.0.0.1:3000", { waitUntil: "networkidle" });
await page.waitForTimeout(1300);
await page.screenshot({ path: "artifacts/home-mobile.png", fullPage: true });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto("http://127.0.0.1:3000/projects/shield-family", { waitUntil: "networkidle" });
await page.waitForTimeout(1300);
await page.screenshot({ path: "artifacts/shield-desktop.png", fullPage: true });
console.log(JSON.stringify({ errors }));
await browser.close();
